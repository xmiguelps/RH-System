    ANO,
    MES,
    DATA_PUBLICACAO,
    CAMINHO_ARQUIVO
FROM HOLERITES
WHERE CAMINHO_ARQUIVO IS NULL
   OR TRIM(CAMINHO_ARQUIVO) = ''
   OR DATA_PUBLICACAO IS NULL;


