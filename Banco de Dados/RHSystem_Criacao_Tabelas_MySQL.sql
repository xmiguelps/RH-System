-- ============================================================
-- 1. NIVEIS_DE_ACESSO
-- ============================================================

CREATE TABLE NIVEIS_DE_ACESSO (
    ID_NIVEL_ACESSO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_NIVEL_ACESSO VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),

    CONSTRAINT UQ_NIVEIS_DE_ACESSO_NOME UNIQUE (NOME_NIVEL_ACESSO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 2. CARGOS
-- ============================================================

CREATE TABLE CARGOS (
    ID_CARGO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_CARGO VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    CARGA_HORARIA DECIMAL(5,2),

    CONSTRAINT UQ_CARGOS_NOME UNIQUE (NOME_CARGO),
    CONSTRAINT CHK_CARGOS_CARGA_HORARIA CHECK (CARGA_HORARIA IS NULL OR CARGA_HORARIA > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 3. FUNCIONARIOS
-- ============================================================
-- ID_GESTOR recebe FK posteriormente porque FUNCIONARIOS e
-- GESTORES possuem uma dependência circular no modelo.

CREATE TABLE FUNCIONARIOS (
    ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    DATA_NASCIMENTO DATE,
    DATA_ADMISSAO DATE NOT NULL,
    DATA_DESLIGAMENTO DATE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    EMAIL VARCHAR(150),
    TELEFONE VARCHAR(30),
    ID_CARGO INT,
    ID_SETOR INT,
    ID_GESTOR INT,
    ID_NIVEL_ACESSO INT,

    CONSTRAINT FK_FUNCIONARIOS_CARGOS
        FOREIGN KEY (ID_CARGO)
        REFERENCES CARGOS(ID_CARGO),

    CONSTRAINT FK_FUNCIONARIOS_NIVEIS_ACESSO
        FOREIGN KEY (ID_NIVEL_ACESSO)
        REFERENCES NIVEIS_DE_ACESSO(ID_NIVEL_ACESSO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 4. SETORES
-- ============================================================
-- ID_GESTOR recebe FK posteriormente porque SETORES e GESTORES
-- também formam uma dependência circular.

CREATE TABLE SETORES (
    ID_SETOR INT AUTO_INCREMENT PRIMARY KEY,
    NOME_SETOR VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    ID_GESTOR INT,

    CONSTRAINT UQ_SETORES_NOME UNIQUE (NOME_SETOR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 5. GESTORES
-- ============================================================

CREATE TABLE GESTORES (
    ID_GESTOR INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    ID_SETOR INT,
    ID_NIVEL_ACESSO INT,

    CONSTRAINT FK_GESTORES_FUNCIONARIOS
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT FK_GESTORES_SETORES
        FOREIGN KEY (ID_SETOR)
        REFERENCES SETORES(ID_SETOR),

    CONSTRAINT FK_GESTORES_NIVEIS_ACESSO
        FOREIGN KEY (ID_NIVEL_ACESSO)
        REFERENCES NIVEIS_DE_ACESSO(ID_NIVEL_ACESSO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 6. FKs que dependem de GESTORES
-- ============================================================

ALTER TABLE FUNCIONARIOS
    ADD CONSTRAINT FK_FUNCIONARIOS_GESTORES
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR);

ALTER TABLE FUNCIONARIOS
    ADD CONSTRAINT FK_FUNCIONARIOS_SETORES
        FOREIGN KEY (ID_SETOR)
        REFERENCES SETORES(ID_SETOR);

ALTER TABLE SETORES
    ADD CONSTRAINT FK_SETORES_GESTORES
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR);

