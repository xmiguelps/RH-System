-- ============================================================
-- 11. PONTOS
-- ============================================================
-- Um registro por funcionario por dia. As batidas individuais
-- ficam em PONTOS_MARCACOES.

CREATE TABLE PONTOS (
    ID_PONTO INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    DATA DATE NOT NULL,
    HORAS_TRABALHADAS DECIMAL(5,2),
    CARGA_HORARIA DECIMAL(5,2),

    CONSTRAINT FK_PONTOS_FUNCIONARIOS
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT UQ_PONTOS_FUNCIONARIO_DATA UNIQUE (ID_FUNCIONARIO, DATA),
    CONSTRAINT CHK_PONTOS_HORAS_TRABALHADAS CHECK (HORAS_TRABALHADAS IS NULL OR HORAS_TRABALHADAS BETWEEN 0 AND 24),
    CONSTRAINT CHK_PONTOS_CARGA_HORARIA CHECK (CARGA_HORARIA IS NULL OR CARGA_HORARIA > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 11.1. PONTOS_MARCACOES
-- ============================================================
-- Cada batida tem data e hora completas. Isso permite multiplas
-- entradas/saidas por dia e tambem jornadas que atravessam meia-noite.

CREATE TABLE PONTOS_MARCACOES (
    ID_MARCACAO INT AUTO_INCREMENT PRIMARY KEY,
    ID_PONTO INT NOT NULL,
    DATA_HORA_MARCACAO DATETIME NOT NULL,
    TIPO_MARCACAO VARCHAR(10) NOT NULL,

    CONSTRAINT FK_PONTOS_MARCACOES_PONTOS
        FOREIGN KEY (ID_PONTO)
        REFERENCES PONTOS(ID_PONTO),

    CONSTRAINT UQ_PONTOS_MARCACOES_ID_PONTO UNIQUE (ID_MARCACAO, ID_PONTO),
    CONSTRAINT CHK_PONTOS_MARCACOES_TIPO CHECK (TIPO_MARCACAO IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT UQ_PONTOS_MARCACOES_PONTO_DATAHORA UNIQUE (ID_PONTO, DATA_HORA_MARCACAO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 12. PONTOS_MANUTENCOES
-- ============================================================

CREATE TABLE PONTOS_MANUTENCOES (
    ID_MANUTENCAO_PONTO INT AUTO_INCREMENT PRIMARY KEY,
    ID_PONTO INT NOT NULL,
    ID_MARCACAO INT,
    ID_FUNCIONARIO INT NOT NULL,
    JUSTIFICATIVA TEXT NOT NULL,
    DATA_SOLICITACAO DATETIME,
    STATUS_SOLICITACAO VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',
    DATA_ANALISE DATETIME,
    ID_GESTOR INT,
    OBSERVACAO TEXT,

    CONSTRAINT FK_PONTOS_MANUTENCOES_PONTOS
        FOREIGN KEY (ID_PONTO)
        REFERENCES PONTOS(ID_PONTO),

    CONSTRAINT FK_PONTOS_MANUTENCOES_MARCACOES
        FOREIGN KEY (ID_MARCACAO, ID_PONTO)
        REFERENCES PONTOS_MARCACOES(ID_MARCACAO, ID_PONTO),

    CONSTRAINT FK_PONTOS_MANUTENCOES_FUNCIONARIOS
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT FK_PONTOS_MANUTENCOES_GESTORES
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR),

    CONSTRAINT CHK_PONTOS_MANUTENCOES_STATUS CHECK (STATUS_SOLICITACAO IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_DATAS CHECK (DATA_SOLICITACAO IS NULL OR DATA_ANALISE IS NULL OR DATA_ANALISE >= DATA_SOLICITACAO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
