    CONSTRAINT CHK_FERIAS_AUTOMATICA
        CHECK (ETAPA_GESTOR_AUTOMATICA = FALSE OR COALESCE(RESULTADO_GESTOR, '') = 'APROVOU'),
    CONSTRAINT CHK_FERIAS_RECUSA_ENCERRA
        CHECK (RESULTADO_GESTOR IS NULL OR RESULTADO_GESTOR <> 'RECUSOU' OR STATUS_FERIAS = 'REJEITADA'),
    CONSTRAINT CHK_FERIAS_CONFIRMACAO_RH
        CHECK ((ID_FUNCIONARIO_RH IS NULL) = (DATA_CONFIRMACAO_RH IS NULL)),
    CONSTRAINT CHK_FERIAS_RH_APOS_GESTOR
        CHECK (ID_FUNCIONARIO_RH IS NULL OR RESULTADO_GESTOR IS NULL OR RESULTADO_GESTOR <> 'RECUSOU'),
    -- Ferias: 13o adiantado e "sugerir outra data"
    CONSTRAINT CHK_FERIAS_RESPOSTA_SUGESTAO
        CHECK (RESPOSTA_SUGESTAO IS NULL OR RESPOSTA_SUGESTAO IN ('ACEITOU', 'RECUSOU', 'EXPIROU')),
    CONSTRAINT CHK_FERIAS_SUGESTAO_DATAS_JUNTAS
        CHECK ((SUGESTAO_DATA_INICIO IS NULL) = (SUGESTAO_DATA_FIM IS NULL)),
    CONSTRAINT CHK_FERIAS_SUGESTAO_DURACAO
        CHECK (SUGESTAO_DATA_INICIO IS NULL
               OR DATEDIFF(SUGESTAO_DATA_FIM, SUGESTAO_DATA_INICIO) + 1 BETWEEN 5 AND 30),
    CONSTRAINT CHK_FERIAS_SUGESTAO_APOS_AQUISITIVO
