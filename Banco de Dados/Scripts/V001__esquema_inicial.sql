    CONSTRAINT CHK_FERIAS_SUGESTAO_E_RESULTADO
        CHECK ((COALESCE(RESULTADO_GESTOR, '') = 'SUGERIU_DATA') = (SUGESTAO_DATA_INICIO IS NOT NULL)),
