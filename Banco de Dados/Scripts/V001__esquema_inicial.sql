        CHECK (RESPOSTA_SUGESTAO IS NULL OR SUGESTAO_DATA_INICIO IS NOT NULL),
    CONSTRAINT CHK_FERIAS_RESPOSTA_E_DATA
        CHECK ((RESPOSTA_SUGESTAO IS NULL) = (DATA_RESPOSTA_SUGESTAO IS NULL)),
    CONSTRAINT CHK_FERIAS_SUGESTAO_NAO_ACEITA_CANCELA
        CHECK (RESPOSTA_SUGESTAO IS NULL OR RESPOSTA_SUGESTAO = 'ACEITOU' OR STATUS_FERIAS = 'CANCELADA'),
    -- Motivo da recusa das ferias (FERIAS.MOTIVO_RECUSA)
    CONSTRAINT CHK_FERIAS_MOTIVO_SO_REJEITADA
        CHECK (MOTIVO_RECUSA IS NULL OR STATUS_FERIAS = 'REJEITADA'),
    CONSTRAINT CHK_FERIAS_MOTIVO_NAO_VAZIO
        CHECK (MOTIVO_RECUSA IS NULL OR TRIM(MOTIVO_RECUSA) <> ''),
    CONSTRAINT CHK_FERIAS_RECUSA_COM_MOTIVO
        CHECK (STATUS_FERIAS <> 'REJEITADA'
               OR MOTIVO_RECUSA IS NOT NULL
               OR (RESULTADO_GESTOR IS NULL AND ID_FUNCIONARIO_RH IS NULL)),
    -- Indices para as listas e filas das fatias 3, 5, 6 e 7
    INDEX IDX_FERIAS_STATUS_PERIODO (STATUS_FERIAS, DATA_FIM, DATA_INICIO),
    INDEX IDX_FERIAS_STATUS_SOLICITACAO (STATUS_FERIAS, DATA_SOLICITACAO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 25. FERIADOS
-- ============================================================
-- Carga anual: cada ano tem seus proprios registros (inclusive os
-- feriados fixos e os moveis, como Sexta-feira Santa), o que
-- preserva o historico e permite consultar feriados de anos
-- passados. Dia, mes e ano ficam em DATA_FERIADO (DAY(), MONTH()
-- e YEAR() extraem cada parte).
-- TIPO_FERIADO define a abrangencia:
--   NACIONAL / EMPRESA : UF e MUNICIPIO nulos
--   ESTADUAL           : UF obrigatoria
--   MUNICIPAL          : UF e MUNICIPIO obrigatorios

CREATE TABLE FERIADOS (
    ID_FERIADO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_FERIADO VARCHAR(100) NOT NULL,
    DATA_FERIADO DATE NOT NULL,
    TIPO_FERIADO VARCHAR(30) NOT NULL,
    UF CHAR(2),
    MUNICIPIO VARCHAR(100),
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    DESCRICAO VARCHAR(255),
    -- Feriados: "repetir todo ano"
    REPETE_TODO_ANO BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT UQ_FERIADOS_DATA_NOME UNIQUE (DATA_FERIADO, NOME_FERIADO),
    CONSTRAINT CHK_FERIADOS_TIPO CHECK (TIPO_FERIADO IN ('NACIONAL', 'ESTADUAL', 'MUNICIPAL', 'EMPRESA')),
    CONSTRAINT CHK_FERIADOS_ABRANGENCIA CHECK (
        (TIPO_FERIADO IN ('NACIONAL', 'EMPRESA') AND UF IS NULL AND MUNICIPIO IS NULL)
        OR (TIPO_FERIADO = 'ESTADUAL' AND UF IS NOT NULL AND MUNICIPIO IS NULL)
        OR (TIPO_FERIADO = 'MUNICIPAL' AND UF IS NOT NULL AND MUNICIPIO IS NOT NULL)
    )
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

