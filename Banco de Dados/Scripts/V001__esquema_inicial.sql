-- ============================================================

CREATE TABLE NIVEIS_DE_ACESSO (
    ID_NIVEL_ACESSO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_NIVEL_ACESSO VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),

    CONSTRAINT UQ_NIVEIS_DE_ACESSO_NOME UNIQUE (NOME_NIVEL_ACESSO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 2. CARGOS
-- ============================================================

CREATE TABLE CARGOS (
    ID_CARGO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_CARGO VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    CARGA_HORARIA DECIMAL(5,2),

    CONSTRAINT UQ_CARGOS_NOME UNIQUE (NOME_CARGO),
    CONSTRAINT CHK_CARGOS_CARGA_HORARIA CHECK (CARGA_HORARIA IS NULL OR CARGA_HORARIA > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 3. FUNCIONARIOS
-- ============================================================
-- ID_GESTOR e ID_SETOR recebem FK posteriormente (secao 6)
-- porque FUNCIONARIOS, SETORES e GESTORES possuem dependencia
-- circular no modelo.
-- EMAIL_CORPORATIVO fica aqui; dados pessoais ficam em
-- FUNCIONARIOS_DETALHES.

CREATE TABLE FUNCIONARIOS (
    ID_FUNCIONARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(150) NOT NULL,
    DATA_NASCIMENTO DATE,
    DATA_ADMISSAO DATE NOT NULL,
    DATA_DESLIGAMENTO DATE,
    ATIVO BOOLEAN NOT NULL DEFAULT TRUE,
    EMAIL_CORPORATIVO VARCHAR(150),
    ID_CARGO INT,
    ID_SETOR INT,
    ID_GESTOR INT,
    ID_NIVEL_ACESSO INT,
    -- Matricula e tipo de contrato em FUNCIONARIOS
    MATRICULA VARCHAR(20) NULL,
    TIPO_CONTRATO VARCHAR(30) NULL,

    CONSTRAINT FK_FUNCIONARIOS_CARGOS
        FOREIGN KEY (ID_CARGO)
        REFERENCES CARGOS(ID_CARGO),

    CONSTRAINT FK_FUNCIONARIOS_NIVEIS_ACESSO
        FOREIGN KEY (ID_NIVEL_ACESSO)
        REFERENCES NIVEIS_DE_ACESSO(ID_NIVEL_ACESSO),

    CONSTRAINT UQ_FUNCIONARIOS_EMAIL_CORPORATIVO UNIQUE (EMAIL_CORPORATIVO),
    CONSTRAINT CHK_FUNCIONARIOS_DATAS CHECK (DATA_DESLIGAMENTO IS NULL OR DATA_DESLIGAMENTO >= DATA_ADMISSAO),
    CONSTRAINT CHK_FUNCIONARIOS_ATIVO_DESLIGAMENTO CHECK (ATIVO = FALSE OR DATA_DESLIGAMENTO IS NULL),
    -- Matricula e tipo de contrato em FUNCIONARIOS
    CONSTRAINT UQ_FUNCIONARIOS_MATRICULA UNIQUE (MATRICULA),
    -- Matricula gerada pelo sistema: contador (SEQUENCIAS) e formato da matricula em FUNCIONARIOS
    CONSTRAINT CHK_FUNCIONARIOS_MATRICULA
        CHECK (MATRICULA IS NULL OR MATRICULA REGEXP '^[0-9]{5}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 4. SETORES
-- ============================================================
-- ID_GESTOR (gestor responsavel pelo setor) recebe FK
-- posteriormente, pela dependencia circular com GESTORES.

CREATE TABLE SETORES (
    ID_SETOR INT AUTO_INCREMENT PRIMARY KEY,
    NOME_SETOR VARCHAR(100) NOT NULL,
    DESCRICAO VARCHAR(255),
    ID_GESTOR INT,

    CONSTRAINT UQ_SETORES_NOME UNIQUE (NOME_SETOR)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 5. GESTORES
-- ============================================================
-- O setor do gestor e definido em SETORES.ID_GESTOR e o nivel
-- de acesso em FUNCIONARIOS.ID_NIVEL_ACESSO, evitando dados
-- duplicados e divergentes.

CREATE TABLE GESTORES (
    ID_GESTOR INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    -- Aprovacao em duas etapas (gestor e depois RH) em PONTOS_MANUTENCOES e FERIAS, mais a chave de aprovacao automatica em GESTORES
    APROVACAO_AUTOMATICA BOOLEAN NOT NULL DEFAULT FALSE,
    APROVACAO_AUTOMATICA_ATE DATE NULL,

    CONSTRAINT FK_GESTORES_FUNCIONARIOS
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT UQ_GESTORES_FUNCIONARIO UNIQUE (ID_FUNCIONARIO),
    -- Aprovacao em duas etapas (gestor e depois RH) em PONTOS_MANUTENCOES e FERIAS, mais a chave de aprovacao automatica em GESTORES
    CONSTRAINT CHK_GESTORES_APROVACAO_AUTOMATICA_ATE
        CHECK (APROVACAO_AUTOMATICA = TRUE OR APROVACAO_AUTOMATICA_ATE IS NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 6. FKs que dependem de GESTORES
-- ============================================================

ALTER TABLE FUNCIONARIOS
    ADD CONSTRAINT FK_FUNCIONARIOS_GESTORES
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR);

ALTER TABLE FUNCIONARIOS
    ADD CONSTRAINT FK_FUNCIONARIOS_SETORES
        FOREIGN KEY (ID_SETOR)
        REFERENCES SETORES(ID_SETOR);

ALTER TABLE SETORES
    ADD CONSTRAINT FK_SETORES_GESTORES
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR);

