-- ============================================================
-- 11. PONTOS
-- ============================================================
-- Um registro por funcionario por dia. As batidas individuais
-- ficam em PONTOS_MARCACOES.

CREATE TABLE PONTOS (
    ID_PONTO INT AUTO_INCREMENT PRIMARY KEY,
    ID_FUNCIONARIO INT NOT NULL,
    DATA DATE NOT NULL,
    HORAS_TRABALHADAS DECIMAL(5,2),
    CARGA_HORARIA DECIMAL(5,2),

    CONSTRAINT FK_PONTOS_FUNCIONARIOS
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT UQ_PONTOS_FUNCIONARIO_DATA UNIQUE (ID_FUNCIONARIO, DATA),
    CONSTRAINT CHK_PONTOS_HORAS_TRABALHADAS CHECK (HORAS_TRABALHADAS IS NULL OR HORAS_TRABALHADAS BETWEEN 0 AND 24),
    CONSTRAINT CHK_PONTOS_CARGA_HORARIA CHECK (CARGA_HORARIA IS NULL OR CARGA_HORARIA > 0),
    -- Indices para as listas e filas das fatias 3, 5, 6 e 7
    INDEX IDX_PONTOS_DATA (DATA)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 11.1. PONTOS_MARCACOES
-- ============================================================
-- Cada batida tem data e hora completas. Isso permite multiplas
-- entradas/saidas por dia e tambem jornadas que atravessam meia-noite.

CREATE TABLE PONTOS_MARCACOES (
    ID_MARCACAO INT AUTO_INCREMENT PRIMARY KEY,
    ID_PONTO INT NOT NULL,
    DATA_HORA_MARCACAO DATETIME NOT NULL,
    TIPO_MARCACAO VARCHAR(10) NOT NULL,
    -- Origem da batida em PONTOS_MARCACOES
    ORIGEM VARCHAR(20) NOT NULL DEFAULT 'SISTEMA',
    -- Quando o RH corrigiu a batida (PONTOS_MARCACOES.DATA_CORRECAO)
    DATA_CORRECAO DATETIME NULL,

    CONSTRAINT FK_PONTOS_MARCACOES_PONTOS
        FOREIGN KEY (ID_PONTO)
        REFERENCES PONTOS(ID_PONTO),

    CONSTRAINT UQ_PONTOS_MARCACOES_ID_PONTO UNIQUE (ID_MARCACAO, ID_PONTO),
    CONSTRAINT CHK_PONTOS_MARCACOES_TIPO CHECK (TIPO_MARCACAO IN ('ENTRADA', 'SAIDA')),
    CONSTRAINT UQ_PONTOS_MARCACOES_PONTO_DATAHORA UNIQUE (ID_PONTO, DATA_HORA_MARCACAO),
    -- Origem da batida em PONTOS_MARCACOES
    CONSTRAINT CHK_PONTOS_MARCACOES_ORIGEM CHECK (ORIGEM IN ('SISTEMA', 'CORRIGIDA_RH')),
    -- Quando o RH corrigiu a batida (PONTOS_MARCACOES.DATA_CORRECAO)
    CONSTRAINT CHK_PONTOS_MARCACOES_DATA_CORRECAO
        CHECK ((ORIGEM = 'CORRIGIDA_RH') = (DATA_CORRECAO IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- 12. PONTOS_MANUTENCOES
-- ============================================================

CREATE TABLE PONTOS_MANUTENCOES (
    ID_MANUTENCAO_PONTO INT AUTO_INCREMENT PRIMARY KEY,
    ID_PONTO INT NOT NULL,
    ID_MARCACAO INT,
    ID_FUNCIONARIO INT NOT NULL,
    JUSTIFICATIVA TEXT NOT NULL,
    DATA_SOLICITACAO DATETIME,
    STATUS_SOLICITACAO VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',
    DATA_ANALISE DATETIME,
    ID_GESTOR INT,
    OBSERVACAO TEXT,
    -- Aprovacao em duas etapas (gestor e depois RH) em PONTOS_MANUTENCOES e FERIAS, mais a chave de aprovacao automatica em GESTORES
    RESULTADO_GESTOR VARCHAR(20) NULL,
    DATA_ETAPA_GESTOR DATETIME NULL,
    ETAPA_GESTOR_AUTOMATICA BOOLEAN NOT NULL DEFAULT FALSE,
    ID_FUNCIONARIO_RH INT NULL,
    DATA_CONFIRMACAO_RH DATETIME NULL,
    -- No maximo um pedido de ajuste pendente por dia de ponto
    CHAVE_PENDENTE INT
        GENERATED ALWAYS AS (IF(STATUS_SOLICITACAO = 'PENDENTE', ID_PONTO, NULL)) STORED NULL,

    CONSTRAINT FK_PONTOS_MANUTENCOES_PONTOS
        FOREIGN KEY (ID_PONTO)
        REFERENCES PONTOS(ID_PONTO),

    CONSTRAINT FK_PONTOS_MANUTENCOES_MARCACOES
        FOREIGN KEY (ID_MARCACAO, ID_PONTO)
        REFERENCES PONTOS_MARCACOES(ID_MARCACAO, ID_PONTO),

    CONSTRAINT FK_PONTOS_MANUTENCOES_FUNCIONARIOS
        FOREIGN KEY (ID_FUNCIONARIO)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),

    CONSTRAINT FK_PONTOS_MANUTENCOES_GESTORES
        FOREIGN KEY (ID_GESTOR)
        REFERENCES GESTORES(ID_GESTOR),

    CONSTRAINT CHK_PONTOS_MANUTENCOES_STATUS CHECK (STATUS_SOLICITACAO IN ('PENDENTE', 'APROVADA', 'REJEITADA')),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_DATAS CHECK (DATA_SOLICITACAO IS NULL OR DATA_ANALISE IS NULL OR DATA_ANALISE >= DATA_SOLICITACAO),
    -- Batidas pedidas no ajuste de ponto (PONTOS_MANUTENCOES_ITENS)
    CONSTRAINT UQ_PONTOS_MANUTENCOES_ID_PONTO UNIQUE (ID_MANUTENCAO_PONTO, ID_PONTO),
    -- Aprovacao em duas etapas (gestor e depois RH) em PONTOS_MANUTENCOES e FERIAS, mais a chave de aprovacao automatica em GESTORES
    CONSTRAINT FK_PONTOS_MANUTENCOES_FUNCIONARIOS_RH
        FOREIGN KEY (ID_FUNCIONARIO_RH)
        REFERENCES FUNCIONARIOS(ID_FUNCIONARIO),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_RESULTADO_GESTOR
        CHECK (RESULTADO_GESTOR IS NULL OR RESULTADO_GESTOR IN ('APROVOU', 'RECUSOU')),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_ETAPA_GESTOR
        CHECK ((RESULTADO_GESTOR IS NULL) = (DATA_ETAPA_GESTOR IS NULL)),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_ETAPA_COM_GESTOR
        CHECK (RESULTADO_GESTOR IS NULL OR ID_GESTOR IS NOT NULL),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_AUTOMATICA
        CHECK (ETAPA_GESTOR_AUTOMATICA = FALSE OR COALESCE(RESULTADO_GESTOR, '') = 'APROVOU'),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_RECUSA_ENCERRA
        CHECK (RESULTADO_GESTOR IS NULL OR RESULTADO_GESTOR <> 'RECUSOU' OR STATUS_SOLICITACAO = 'REJEITADA'),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_CONFIRMACAO_RH
        CHECK ((ID_FUNCIONARIO_RH IS NULL) = (DATA_CONFIRMACAO_RH IS NULL)),
    CONSTRAINT CHK_PONTOS_MANUTENCOES_RH_APOS_GESTOR
        CHECK (ID_FUNCIONARIO_RH IS NULL OR RESULTADO_GESTOR IS NULL OR RESULTADO_GESTOR <> 'RECUSOU'),
    -- No maximo um pedido de ajuste pendente por dia de ponto
    CONSTRAINT UQ_PONTOS_MANUTENCOES_UM_PENDENTE UNIQUE (CHAVE_PENDENTE),
    -- Indices para as listas e filas das fatias 3, 5, 6 e 7
    INDEX IDX_PONTOS_MANUTENCOES_STATUS_DATA (STATUS_SOLICITACAO, DATA_SOLICITACAO)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

