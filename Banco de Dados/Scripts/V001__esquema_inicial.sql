    LEMBRA_ANTES_DO_FIM BOOLEAN NOT NULL DEFAULT FALSE,
    -- Treinamento encerrado (TREINAMENTOS.ENCERRADO_EM)
    ENCERRADO_EM DATETIME NULL,

    CONSTRAINT CHK_TREINAMENTOS_DATAS CHECK (DATA_INICIO IS NULL OR DATA_FIM IS NULL OR DATA_FIM >= DATA_INICIO),
    -- Treinamentos: rascunho/publicacao, publico e certificado
