-- ============================================================
-- V039 - Quando o RH corrigiu a batida (PONTOS_MARCACOES.DATA_CORRECAO)
-- Fatia 3 (ponto). Lacuna achada na analise do contrato.
-- ============================================================
-- POR QUE
--   O Figma mostra "Saida corrigida pelo RH em 07/10" na linha do dia, e o
--   contrato promete esse "em 07/10" no campo corrigidaEmUtc de cada batida
--   (contrato/fontes/30-fatia-3-ponto.yaml, schema PontoMarcacao). O V008
--   criou so ORIGEM (SISTEMA ou CORRIGIDA_RH) e deixou o "quando" para o log
--   de auditoria, e o contrato escreveu "o valor vem do log de auditoria".
--   A tabela de auditoria (V037) guarda ENTIDADE e ID_REGISTRO, entao DA para
--   achar o evento de uma batida. Duas coisas pesam contra depender so dele:
--   - a correcao do RH e um PUT do dia inteiro (varias batidas num pedido), e
--     o "quando" de CADA batida so existe no log se a aplicacao gravar uma
--     mudanca por batida corrigida, o que o contrato nao diz,
--   - o espelho do mes passa a consultar o log para cada batida corrigida.
--   Uma coluna na propria batida resolve as duas coisas, e o V008 ja previa
--   isso ("se voce preferir ter isso na propria batida, e so acrescentar
--   colunas"). O custo e guardar o dado em dois lugares (a coluna e o log).
--
-- ESTE SCRIPT FAZ PARTE DO ESQUEMA
--   O contrato adotou DATA_CORRECAO como a fonte do campo corrigidaEmUtc
--   (decisao de 2026-10-30), entao o V039 deve ser aplicado. O log de
--   auditoria continua guardando QUEM fez cada correcao.
--
-- O QUE ESTE SCRIPT FAZ
--   Acrescenta DATA_CORRECAO em PONTOS_MARCACOES e um CHECK que amarra a
--   coluna a ORIGEM: a batida corrigida pelo RH tem a data da correcao, e a
--   batida do sistema nao tem. A coluna e e o CHECK entram na mesma
--   instrucao: se alguma linha antiga violasse o CHECK, nada seria alterado.
--
-- FUSO
--   DATA_CORRECAO e DATETIME no fuso -03:00 (regra de fuso do roadmap, decisao
--   4). Nao ha trigger em PONTOS_MARCACOES, entao quem grava e a aplicacao,
--   que converte para -03:00 na fronteira (ou deixa o banco usar NOW(), que
--   com o servidor em -03:00 da o mesmo valor).
--
-- DECISOES QUE VOCE PODE REVER
--   1) Nao guarda QUEM corrigiu: o contrato nao pede (so o "quando"), e o
--      log de auditoria continua guardando quem fez cada correcao.
--   2) Nao ha valor padrao de proposito: a data da correcao e o momento em
--      que o RH confirmou, e nao o da gravacao de outra coisa.
--
-- O QUE FICA COM A APLICACAO
--   - Ao corrigir ou incluir uma batida (PUT .../ponto/dias/{dia} ou a
--     aprovacao de um pedido de ajuste), gravar ORIGEM = 'CORRIGIDA_RH' e
--     DATA_CORRECAO juntas, no mesmo UPDATE ou INSERT.
--   - O contrato ja descreve corrigidaEmUtc como vindo desta coluna.
--
-- NENHUM TRIGGER E ALTERADO POR ESTE SCRIPT.
-- ============================================================

ALTER TABLE PONTOS_MARCACOES
    ADD COLUMN DATA_CORRECAO DATETIME NULL,
    -- ORIGEM e NOT NULL (V008), entao a comparacao nunca da NULL
    ADD CONSTRAINT CHK_PONTOS_MARCACOES_DATA_CORRECAO
        CHECK ((ORIGEM = 'CORRIGIDA_RH') = (DATA_CORRECAO IS NOT NULL));
