USE rh_system;

DROP FUNCTION IF EXISTS FN_CALCULAR_SALDO_BANCO_HORAS;
DROP FUNCTION IF EXISTS FN_CALCULAR_TEMPO_EMPRESA_DIAS;
DROP FUNCTION IF EXISTS FN_VERIFICAR_TREINAMENTO_CONCLUIDO;
DROP FUNCTION IF EXISTS FN_CALCULAR_PERCENTUAL_TREINAMENTO;
DROP FUNCTION IF EXISTS FN_CALCULAR_HORAS_TRABALHADAS;
DROP FUNCTION IF EXISTS FN_CONTAR_AVISOS_NAO_LIDOS;
DROP FUNCTION IF EXISTS FN_VERIFICAR_CONSISTENCIA_PONTO;
DROP FUNCTION IF EXISTS FN_CALCULAR_HORAS_PONTO;

DELIMITER $$

-- 1. Retorna créditos menos débitos do banco de horas.
CREATE FUNCTION FN_CALCULAR_SALDO_BANCO_HORAS(P_ID_FUNCIONARIO INT)
RETURNS DECIMAL(10,2)
READS SQL DATA
BEGIN
    DECLARE V_SALDO DECIMAL(10,2) DEFAULT 0.00;

    SELECT COALESCE(SUM(
        CASE
            WHEN UPPER(TIPO_LANCAMENTO) = 'CREDITO' THEN QUANTIDADE
            WHEN UPPER(TIPO_LANCAMENTO) = 'DEBITO' THEN -QUANTIDADE
            ELSE 0
        END
    ), 0.00)
    INTO V_SALDO
    FROM BANCOS_HORAS
    WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO;

    RETURN V_SALDO;
END$$

-- 2. Tempo de empresa em dias; considera desligamento se houver.
CREATE FUNCTION FN_CALCULAR_TEMPO_EMPRESA_DIAS(P_ID_FUNCIONARIO INT)
RETURNS INT
READS SQL DATA
BEGIN
    DECLARE V_ADMISSAO DATE DEFAULT NULL;
    DECLARE V_DESLIGAMENTO DATE DEFAULT NULL;
    DECLARE V_DATA_FINAL DATE DEFAULT NULL;

    SELECT DATA_ADMISSAO, DATA_DESLIGAMENTO
    INTO V_ADMISSAO, V_DESLIGAMENTO
    FROM FUNCIONARIOS
    WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO
    LIMIT 1;

    IF V_ADMISSAO IS NULL THEN
        RETURN NULL;
    END IF;

    SET V_DATA_FINAL = COALESCE(V_DESLIGAMENTO, CURDATE());

    IF V_DATA_FINAL < V_ADMISSAO THEN
        RETURN NULL;
    END IF;

    RETURN DATEDIFF(V_DATA_FINAL, V_ADMISSAO);
END$$

-- 3. Retorna 1 se o funcionário concluiu o treinamento; caso contrário, 0.
CREATE FUNCTION FN_VERIFICAR_TREINAMENTO_CONCLUIDO(
    P_ID_FUNCIONARIO INT,
    P_ID_TREINAMENTO INT
)
RETURNS TINYINT
READS SQL DATA
BEGIN
    DECLARE V_QTD INT DEFAULT 0;

    SELECT COUNT(*)
    INTO V_QTD
    FROM TREINAMENTOS_FUNCIONARIOS
    WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO
      AND ID_TREINAMENTO = P_ID_TREINAMENTO
      AND UPPER(STATUS_TREINAMENTO) = 'CONCLUIDO';

    RETURN IF(V_QTD > 0, 1, 0);
END$$

-- 4. Percentual de treinamentos concluídos por funcionário (0 a 100).
CREATE FUNCTION FN_CALCULAR_PERCENTUAL_TREINAMENTO(P_ID_FUNCIONARIO INT)
RETURNS DECIMAL(5,2)
READS SQL DATA
BEGIN
    DECLARE V_TOTAL INT DEFAULT 0;
    DECLARE V_CONCLUIDOS INT DEFAULT 0;

    SELECT COUNT(*),
           COALESCE(SUM(CASE
               WHEN UPPER(STATUS_TREINAMENTO) = 'CONCLUIDO' THEN 1
               ELSE 0
           END), 0)
    INTO V_TOTAL, V_CONCLUIDOS
    FROM TREINAMENTOS_FUNCIONARIOS
    WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO;

    IF V_TOTAL = 0 THEN
        RETURN 0.00;
    END IF;

    RETURN ROUND((V_CONCLUIDOS / V_TOTAL) * 100, 2);
END$$

-- 5. Verifica se as marcações do registro diário alternam entre entrada e saída.
-- Retornos: CONSISTENTE, PONTO INCONSISTENTE, SEM MARCACOES, PONTO INEXISTENTE.
CREATE FUNCTION FN_VERIFICAR_CONSISTENCIA_PONTO(P_ID_PONTO INT)
RETURNS VARCHAR(30)
READS SQL DATA
BEGIN
    DECLARE V_TIPO VARCHAR(10);
    DECLARE V_ESPERADO VARCHAR(10) DEFAULT 'ENTRADA';
    DECLARE V_TOTAL INT DEFAULT 0;
    DECLARE V_FIM BOOLEAN DEFAULT FALSE;

    DECLARE CUR_MARCACOES CURSOR FOR
        SELECT TIPO_MARCACAO
        FROM PONTOS_MARCACOES
        WHERE ID_PONTO = P_ID_PONTO
        ORDER BY DATA_HORA_MARCACAO, ID_MARCACAO;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_FIM = TRUE;

    IF NOT EXISTS (SELECT 1 FROM PONTOS WHERE ID_PONTO = P_ID_PONTO) THEN
        RETURN 'PONTO INEXISTENTE';
    END IF;

    SELECT COUNT(*) INTO V_TOTAL
    FROM PONTOS_MARCACOES
    WHERE ID_PONTO = P_ID_PONTO;

    IF V_TOTAL = 0 THEN
        RETURN 'SEM MARCACOES';
    END IF;

    OPEN CUR_MARCACOES;

    LEITURA: LOOP
        FETCH CUR_MARCACOES INTO V_TIPO;
        IF V_FIM THEN
            LEAVE LEITURA;
        END IF;

        IF V_TIPO <> V_ESPERADO THEN
            CLOSE CUR_MARCACOES;
            RETURN 'PONTO INCONSISTENTE';
        END IF;

        IF V_TIPO = 'ENTRADA' THEN
            SET V_ESPERADO = 'SAIDA';
        ELSE
            SET V_ESPERADO = 'ENTRADA';
        END IF;
    END LOOP;

    CLOSE CUR_MARCACOES;

    IF V_ESPERADO = 'SAIDA' THEN
        RETURN 'PONTO INCONSISTENTE';
    END IF;

    RETURN 'CONSISTENTE';
END$$

-- 6. Calcula as horas de um único registro diário de ponto.
-- Retorna NULL se não houver marcações completas/consistentes.
CREATE FUNCTION FN_CALCULAR_HORAS_PONTO(P_ID_PONTO INT)
RETURNS DECIMAL(7,2)
READS SQL DATA
BEGIN
    DECLARE V_TIPO VARCHAR(10);
    DECLARE V_DATA_HORA DATETIME;
    DECLARE V_ENTRADA DATETIME DEFAULT NULL;
    DECLARE V_TOTAL_SEGUNDOS BIGINT DEFAULT 0;
    DECLARE V_FIM BOOLEAN DEFAULT FALSE;
    DECLARE V_STATUS VARCHAR(30);

    DECLARE CUR_MARCACOES CURSOR FOR
        SELECT DATA_HORA_MARCACAO, TIPO_MARCACAO
        FROM PONTOS_MARCACOES
        WHERE ID_PONTO = P_ID_PONTO
        ORDER BY DATA_HORA_MARCACAO, ID_MARCACAO;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_FIM = TRUE;

    SET V_STATUS = FN_VERIFICAR_CONSISTENCIA_PONTO(P_ID_PONTO);
    IF V_STATUS <> 'CONSISTENTE' THEN
        RETURN NULL;
    END IF;

    OPEN CUR_MARCACOES;

    CALCULO: LOOP
        FETCH CUR_MARCACOES INTO V_DATA_HORA, V_TIPO;
        IF V_FIM THEN
            LEAVE CALCULO;
        END IF;

        IF V_TIPO = 'ENTRADA' THEN
            SET V_ENTRADA = V_DATA_HORA;
        ELSE
            SET V_TOTAL_SEGUNDOS = V_TOTAL_SEGUNDOS
                + TIMESTAMPDIFF(SECOND, V_ENTRADA, V_DATA_HORA);
            SET V_ENTRADA = NULL;
        END IF;
    END LOOP;

    CLOSE CUR_MARCACOES;
    RETURN ROUND(V_TOTAL_SEGUNDOS / 3600, 2);
END$$

-- 7. Soma horas trabalhadas do funcionário no período informado (datas inclusivas).
-- Pontos sem marcações ou inconsistentes são ignorados; retorna 0 se não houver horas válidas.
CREATE FUNCTION FN_CALCULAR_HORAS_TRABALHADAS(
    P_ID_FUNCIONARIO INT,
    P_DATA_INICIAL DATE,
    P_DATA_FINAL DATE
)
RETURNS DECIMAL(10,2)
READS SQL DATA
BEGIN
    DECLARE V_ID_PONTO INT;
    DECLARE V_HORAS DECIMAL(7,2);
    DECLARE V_TOTAL DECIMAL(10,2) DEFAULT 0.00;
    DECLARE V_FIM BOOLEAN DEFAULT FALSE;

    DECLARE CUR_PONTOS CURSOR FOR
        SELECT ID_PONTO
        FROM PONTOS
        WHERE ID_FUNCIONARIO = P_ID_FUNCIONARIO
          AND DATA BETWEEN P_DATA_INICIAL AND P_DATA_FINAL
        ORDER BY DATA;

    DECLARE CONTINUE HANDLER FOR NOT FOUND SET V_FIM = TRUE;

    IF P_DATA_INICIAL IS NULL OR P_DATA_FINAL IS NULL
       OR P_DATA_FINAL < P_DATA_INICIAL THEN
        RETURN NULL;
    END IF;

    OPEN CUR_PONTOS;

    LEITURA_PONTOS: LOOP
        FETCH CUR_PONTOS INTO V_ID_PONTO;
        IF V_FIM THEN
            LEAVE LEITURA_PONTOS;
        END IF;

        SET V_HORAS = FN_CALCULAR_HORAS_PONTO(V_ID_PONTO);
        IF V_HORAS IS NOT NULL THEN
            SET V_TOTAL = V_TOTAL + V_HORAS;
        END IF;
    END LOOP;

    CLOSE CUR_PONTOS;
    RETURN V_TOTAL;
END$$

-- 8. Conta avisos não lidos, publicados e ainda não expirados.
CREATE FUNCTION FN_CONTAR_AVISOS_NAO_LIDOS(P_ID_FUNCIONARIO INT)
RETURNS INT
READS SQL DATA
BEGIN
    DECLARE V_TOTAL INT DEFAULT 0;

    SELECT COUNT(*) INTO V_TOTAL
    FROM AVISOS_VISUALIZACOES AV
    INNER JOIN AVISOS A ON A.ID_AVISO = AV.ID_AVISO
    WHERE AV.ID_FUNCIONARIO = P_ID_FUNCIONARIO
      AND AV.VISUALIZADO = FALSE
      AND (A.DATA_PUBLICACAO IS NULL OR A.DATA_PUBLICACAO <= NOW())
      AND (A.DATA_EXPIRACAO IS NULL OR A.DATA_EXPIRACAO >= NOW());

    RETURN V_TOTAL;
END$$

