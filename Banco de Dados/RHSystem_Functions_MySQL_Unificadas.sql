-- 1) BANCOS_HORAS.TIPO_LANCAMENTO deve usar 'CREDITO' e 'DEBITO'.
-- 2) As marcações de ponto ficam em PONTOS_MARCACOES.
-- 3) FN_CALCULAR_HORAS_PONTO calcula um único dia/registro de ponto.
-- 4) FN_CALCULAR_HORAS_TRABALHADAS soma as horas dos pontos
--    consistentes de um funcionário em um período.
-- 5) Horas de pontos inconsistentes não entram no total do período.
